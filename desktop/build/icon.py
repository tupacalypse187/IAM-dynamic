#!/usr/bin/env python3
"""Generate IAM-Dynamic Desktop app icons from code (no design tools needed).

Outputs desktop/build/icons/{icon.png, icon.ico, icon.icns}:
  - icon.png  1024px master + linux icon
  - icon.ico  Windows icon (multi-size)
  - icon.icns macOS icon (via iconutil + sips; darwin only)

Requires: pillow (`pip install pillow`). The script is idempotent — rerun
anytime; icons are gitignored build artifacts, regenerated by `npm run icons`
before every packaged build.
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

try:
    from PIL import Image, ImageDraw
except ImportError:
    print("icon.py: pillow is required — pip install pillow", file=sys.stderr)
    sys.exit(2)

SIZE = 1024
OUT = Path(__file__).resolve().parent / "icons"

# App palette (matches the renderer theme).
NAVY = (15, 23, 42)
INDIGO = (49, 67, 225)
LIGHT = (147, 197, 253)
WHITE = (255, 255, 255)


def rounded_mask(size: int, radius: int) -> Image.Image:
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, size, size], radius=radius, fill=255)
    return mask


def base() -> Image.Image:
    """Navy rounded square with a diagonal indigo sheen + white shield."""
    img = Image.new("RGB", (SIZE, SIZE), NAVY)
    sheen = Image.new("RGB", (SIZE, SIZE), INDIGO)
    grad = Image.new("L", (1, SIZE))
    for y in range(SIZE):
        grad.putpixel((0, y), int(90 * (1 - y / SIZE)))
    sheen.putalpha(grad.resize((SIZE, SIZE)))
    img = Image.composite(sheen, img, sheen.split()[3])
    img.putalpha(rounded_mask(SIZE, SIZE // 5))

    d = ImageDraw.Draw(img, "RGBA")
    c = SIZE // 2
    # Shield outline.
    shield_w, shield_top, shield_bot = SIZE * 0.30, SIZE * 0.26, SIZE * 0.72
    shield = [
        (c - shield_w, shield_top),
        (c + shield_w, shield_top),
        (c + shield_w, SIZE * 0.48),
        (c, shield_bot),
        (c - shield_w, SIZE * 0.48),
    ]
    d.polygon(shield, outline=WHITE, width=SIZE // 32)
    # Keyhole: circle + tapered slot.
    kr = SIZE * 0.055
    ky = SIZE * 0.44
    d.ellipse([c - kr, ky - kr, c + kr, ky + kr], fill=LIGHT)
    d.polygon(
        [(c - kr * 0.55, ky + kr * 0.6), (c + kr * 0.55, ky + kr * 0.6),
         (c + kr * 0.28, ky + kr * 2.1), (c - kr * 0.28, ky + kr * 2.1)],
        fill=LIGHT,
    )
    return img


def write_png_ico(img: Image.Image) -> Path:
    OUT.mkdir(parents=True, exist_ok=True)
    png = OUT / "icon.png"
    img.save(png)
    rgb = img.convert("RGB")
    rgb.save(OUT / "icon.ico", sizes=[(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    return png


def _png_bytes(img: Image.Image, px: int) -> bytes:
    import io as _io

    buf = _io.BytesIO()
    img.resize((px, px), Image.LANCZOS).save(buf, format="PNG")
    return buf.getvalue()


def write_icns_flat(img: Image.Image) -> None:
    """Write .icns directly (no iconutil): 'icns' magic + PNG-compressed
    elements. Type codes per Apple's IconFamily mapping (matches what
    iconutil emits for a full iconset): ic13=16, ic14=32(@2x of 16),
    ic11=32, ic12=64, ic07=128, ic08=256, ic09=512, ic10=1024."""
    import struct as _struct

    elements = [
        (b"ic13", 16),
        (b"ic14", 32),
        (b"ic11", 32),
        (b"ic12", 64),
        (b"ic07", 128),
        (b"ic08", 256),
        (b"ic09", 512),
        (b"ic10", 1024),
    ]
    blob = bytearray()
    for ostype, px in elements:
        payload = _png_bytes(img, px)
        blob += ostype + _struct.pack(">I", 8 + len(payload)) + payload
    out = OUT / "icon.icns"
    out.write_bytes(b"icns" + _struct.pack(">I", 8 + len(blob)) + bytes(blob))


def write_icns(master: Path, img: Image.Image) -> None:
    """Build .icns via iconutil when it works; otherwise write it directly."""
    iconset = OUT / "icon.iconset"
    if (
        sys.platform == "darwin"
        and shutil.which("iconutil") is not None
        and shutil.which("sips") is not None
    ):
        iconset.mkdir(exist_ok=True)
        try:
            for size in (16, 32, 128, 256, 512):
                for scale, suffix in ((1, ""), (2, "@2x")):
                    px = size * scale
                    if px > SIZE:
                        continue
                    subprocess.run(
                        ["sips", "-z", str(px), str(px), str(master),
                         "--out", str(iconset / f"icon_{size}x{size}{suffix}.png")],
                        check=True, capture_output=True,
                    )
            subprocess.run(
                ["iconutil", "-c", "icns", str(iconset), "-o", str(OUT / "icon.icns")],
                check=True, capture_output=True,
            )
            shutil.rmtree(iconset)
            print("icon.py: .icns via iconutil")
            return
        except subprocess.CalledProcessError:
            print("icon.py: iconutil failed, writing .icns directly")
            shutil.rmtree(iconset, ignore_errors=True)
    else:
        print("icon.py: iconutil unavailable, writing .icns directly")
    write_icns_flat(img)


def main() -> None:
    img = base()
    master = write_png_ico(img)
    write_icns(master, img)
    print(f"icon.py: wrote {sorted(p.name for p in OUT.iterdir() if p.is_file())}")


if __name__ == "__main__":
    main()
